import type { ReportData } from "../schema.js";
import { CLIENT_JS, CSS } from "./assets.js";
import { escapeHtml, safeJsonForScript } from "./escape.js";

/**
 * Render the whole report as one self-contained HTML page. The data is embedded once as JSON;
 * the client script builds the DOM with textContent. No external URLs of any kind.
 */
export function renderHtml(data: ReportData): string {
  // `command` duplicates `summary` (first 200 chars) and is only needed by the loop heuristics, which
  // have already run; leave it out of the page so less command text is embedded.
  const payload = { ...data, events: data.events.map(({ command: _command, ...e }) => e) };
  const title = `rig-replay: ${data.repo.root}`;
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="generator" content="rig-replay">
<title>${escapeHtml(title)}</title>
<style>${CSS}</style>
</head>
<body>
<main>
<header id="hdr" class="panel"></header>
<noscript><p>This report needs JavaScript to render. The raw data is embedded in the page source (script#rig-data).</p></noscript>
<h2>Warnings</h2>
<section id="warnings"></section>
<h2>Timeline</h2>
<section class="panel" id="timeline"></section>
<h2>Events</h2>
<section class="panel">
<div class="filters" id="filters"></div>
<div class="note" id="shown"></div>
</section>
<table id="events">
<thead><tr><th>time</th><th>lane</th><th>kind</th><th>files</th><th>summary</th><th>status</th><th>evidence</th></tr></thead>
<tbody id="events-body"></tbody>
</table>
<footer>
<h2>Tokens and estimated cost</h2>
<section class="panel" id="tokens"></section>
<section class="panel" id="prices" style="margin-top:10px"></section>
<h2>Parser notes</h2>
<section class="panel" id="notes"></section>
<p class="note">Possible conflicts and loops are heuristics built from edits observed in logs. Edits made via shell commands
(for example sed -i, cat &gt; file, code generators) are not seen, and a possible conflict is not proof that work was lost.
Costs are estimates from the price table above. Generated by rig-replay from local log files; this page makes no network requests.</p>
</footer>
</main>
<script type="application/json" id="rig-data">${safeJsonForScript(payload)}</script>
<script>${CLIENT_JS}</script>
</body>
</html>
`;
}
